const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || "playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const fixture = JSON.parse(fs.readFileSync("../cp-art-qa-session.json", "utf8"));
if (fixture.base !== "http://127.0.0.1:5190") throw new Error("Only isolated localhost data is accepted.");
const checks = [], errors = [];
const check = (name, value) => { assert.ok(value, name); checks.push(name); };
async function api(url, method = "GET", body, token = fixture.adminToken, status = 200) {
  const response = await fetch(fixture.base + url, { method, headers: { "content-type": "application/json", ...(token ? { authorization: `Bearer ${token}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
  const result = await response.json(); assert.equal(response.status, status, JSON.stringify(result)); return result;
}
async function artwork() { return (await api("/api/art/admin/artworks")).artworks.find(work => work._id === fixture.artworkId); }
(async () => {
  const payload = { language: "en", entries: [{ key: "title", text: "L’autre rive" }] };
  await api("/api/art/admin/translate", "POST", payload, null, 401);
  await api("/api/art/admin/translate", "POST", payload, fixture.viewerToken, 403);
  check("Translation requires the existing catalogue permission", true);
  await api("/api/art/admin/translate", "POST", { ...payload, entries: [{ key: "providerReference", text: "private" }] }, fixture.adminToken, 400);
  check("Translation API rejects private supplier fields", true);
  const browser = await chromium.launch({ channel: "msedge", headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
    await context.addInitScript(({ token, user }) => { if (location.origin !== "http://127.0.0.1:5185") return; localStorage.setItem("token", token); localStorage.setItem("user", JSON.stringify(user)); }, { token: fixture.adminToken, user: fixture.adminUser });
    await context.route("https://res.cloudinary.com/cp-art-qa/**", route => route.fulfill({ path: path.resolve("public/art/studies/le-passage.webp"), contentType: "image/webp" }));
    const page = await context.newPage(); page.on("pageerror", error => errors.push(error.message));
    await page.goto("http://127.0.0.1:5185/secure-admin-dashboard-2024/cp-art");
    await page.getByRole("heading", { name: "Catalogue des œuvres", exact: true }).waitFor();
    const work = await artwork();
    const card = page.locator(".MuiPaper-root").filter({ has: page.getByText(work.title.fr, { exact: true }) }).last();
    await card.getByRole("button", { name: "Modifier la fiche", exact: true }).click();
    await page.getByRole("tab", { name: "EN", exact: true }).click();
    await page.getByLabel("Titre (EN)", { exact: true }).fill("My manually chosen title");
    await page.getByRole("button", { name: "Traduire vers EN", exact: true }).click();
    await page.getByText("Traduction EN ajoutée", { exact: false }).waitFor();
    check("English translation preserves manually entered titles", await page.getByLabel("Titre (EN)", { exact: true }).inputValue() === "My manually chosen title");
    check("English story is filled from French", (await page.getByLabel("Histoire et signification (EN)", { exact: true }).inputValue()).startsWith("EN:"));
    check("Translated photo descriptions are included", (await page.getByLabel("Description photo 1 (EN)", { exact: true }).inputValue()).startsWith("EN:"));
    check("Translation alone never saves or publishes the artwork", (await artwork()).__v === work.__v);
    await page.getByRole("button", { name: "Traduire vers NL", exact: true }).click();
    await page.getByText("Traduction NL ajoutée", { exact: false }).waitFor();
    check("Dutch translation fills its own language tab", (await page.getByLabel("Titre (NL)", { exact: true }).inputValue()).startsWith("NL:"));
    await page.getByLabel("Histoire et signification (NL)", { exact: true }).fill("Mijn nagelezen verhaal");
    await page.getByRole("tab", { name: "FR", exact: true }).click();
    await page.getByLabel("Histoire et signification (FR)", { exact: true }).fill("QA_TRANSLATION_FAIL");
    await page.getByRole("tab", { name: "EN", exact: true }).click();
    await page.getByLabel("Histoire et signification (EN)", { exact: true }).fill("");
    await page.getByRole("button", { name: "Traduire vers EN", exact: true }).click();
    await page.getByText("La traduction n’a pas abouti.", { exact: false }).waitFor();
    check("Provider failure keeps the editor and existing translations intact", await page.getByLabel("Titre (EN)", { exact: true }).inputValue() === "My manually chosen title");
    await page.getByRole("tab", { name: "FR", exact: true }).click();
    check("Provider failure preserves the French source", await page.getByLabel("Histoire et signification (FR)", { exact: true }).inputValue() === "QA_TRANSLATION_FAIL");
    await page.getByLabel("Histoire et signification (FR)", { exact: true }).fill("Un nouveau récit avant traduction.");
    let release;
    const held = new Promise(resolve => { release = resolve; });
    const routePattern = "**/api/art/admin/translate";
    await page.route(routePattern, async route => { await held; await route.continue(); });
    const sent = page.waitForRequest(request => request.url().endsWith("/api/art/admin/translate"));
    await page.getByRole("button", { name: "Traduire vers EN", exact: true }).click(); await sent;
    await page.getByLabel("Histoire et signification (FR)", { exact: true }).fill("Le récit modifié pendant l’attente.");
    release(); await page.getByText("Traduction EN ajoutée", { exact: false }).waitFor();
    check("A changed source does not receive an out-of-date translation", await page.getByLabel("Histoire et signification (EN)", { exact: true }).inputValue() === "");
    await page.unroute(routePattern);
    await page.getByRole("button", { name: "Traduire vers EN", exact: true }).click();
    await page.waitForFunction(() => [...document.querySelectorAll("textarea")].some(element => element.value.startsWith("EN: Le récit modifié")));
    await page.getByRole("button", { name: "Enregistrer la fiche", exact: true }).click();
    await page.getByRole("dialog").waitFor({ state: "hidden" });
    const saved = await artwork();
    check("Explicit save persists reviewed text and translations", saved.title.en === "My manually chosen title" && saved.story.nl === "Mijn nagelezen verhaal" && saved.story.en.startsWith("EN: Le récit modifié"));
    await card.getByRole("button", { name: "Modifier la fiche", exact: true }).click();
    await page.screenshot({ path: "../cp-art-translation-editor-desktop.png", fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByText("Traduction automatique depuis le français", { exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: "../cp-art-translation-editor-mobile.png", fullPage: true });
    check("Translation controls fit the mobile editor", await page.getByRole("dialog").evaluate(element => element.scrollWidth <= element.clientWidth + 1));
    check("No uncaught browser errors", errors.length === 0);
    fs.writeFileSync("../cp-art-translation-verification.json", JSON.stringify({ checkedAt: new Date().toISOString(), count: checks.length, isolatedDatabase: true, providerSimulated: true, checks }, null, 2) + "\n");
    console.log(`${checks.length} translation flow checks passed with a simulated provider and isolated data.`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
