const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || "playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const fixture = JSON.parse(fs.readFileSync(process.env.CP_ART_QA_SESSION_PATH || "../cp-art-qa-session.json", "utf8"));
const base = "http://127.0.0.1:5185";
const checks = [];
const output = path.resolve("docs/art-preview");
const check = (name, value) => { assert.ok(value, name); checks.push(name); };
const delaySafeFill = async (locator, value) => { await locator.fill(value); await locator.press("Tab"); };
(async () => {
  const browser = await chromium.launch({ channel: "msedge", headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
  await context.route("https://res.cloudinary.com/cp-art-qa/**", async route => {
    const file = route.request().url().includes("detail.webp") ? "memoire-des-lieux.webp" : "le-passage.webp";
    await route.fulfill({ path: path.resolve("public/art/studies", file), contentType: "image/webp" });
  });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  async function open(route) { await page.goto(base + route); await page.locator(".art-header").waitFor(); const decline = page.getByRole("button", { name: "Refuser", exact: true }); if (await decline.isVisible()) await decline.click(); }
  try {
    await open("/fr/art/galerie");
    await page.locator(".art-work-card").waitFor();
    check("Live gallery shows published data rather than sample fixtures", (await page.locator(".art-work-card").innerText()).includes("QA") && await page.locator(".art-work-card").count() === 1);
    check("Private draft is absent", !(await page.locator("main").innerText()).includes("Brouillon privé"));
    await page.locator(".art-work-card").click();
    const secondPhoto = await page.locator(".art-photo-thumbnails button img").last().getAttribute("src");
    await page.locator(".art-photo-thumbnails button").last().click();
    check("Real artwork supports multiple photographs", await page.locator(".art-product__canvas img").getAttribute("src") === secondPhoto);
    await page.getByRole("button", { name: "Affiche encadrée", exact: true }).click();
    check("Variant changes actual displayed price", (await page.locator(".art-real-price").innerText()).includes("39,90"));
    await page.getByRole("button", { name: "Ajouter à ma sélection", exact: true }).click();
    await page.locator(".art-selection-total").waitFor();
    check("Cart is repriced by server", (await page.locator(".art-selection-total").innerText()).includes("39,90"));
    await page.locator(".art-selection-line input[type=number]").fill("2");
    await page.waitForFunction(() => document.querySelector(".art-selection-total")?.textContent.includes("79,80"));
    check("Quantity updates server quote", (await page.locator(".art-selection-total").innerText()).includes("79,80"));
    await page.reload(); await page.locator(".art-selection-total").waitFor();
    check("Selection persists on reload", await page.locator(".art-selection-line input").inputValue() === "2");
    await page.getByRole("button", { name: "Envoyer ma demande à l’atelier", exact: true }).click();
    check("Enquiry form checks contact details and consent", await page.locator(".art-form-error").isVisible());
    await page.getByLabel("Votre nom", { exact: true }).fill("Client interface QA");
    await page.getByLabel("Votre adresse email", { exact: true }).fill("interface@example.test");
    await page.getByLabel("Un message pour l’atelier (facultatif)").fill("Vérification du parcours complet en base temporaire.");
    await page.getByLabel("J’accepte l’utilisation de mes coordonnées pour recevoir une réponse à cette demande.").check();
    await page.screenshot({ path: path.join(output, "selection-live-desktop.png"), fullPage: true });
    await page.getByRole("button", { name: "Envoyer ma demande à l’atelier", exact: true }).click();
    await page.locator(".art-request-success").waitFor();
    const submittedReference = await page.locator(".art-request-success strong").innerText();
    check("Submission receives an actual stored reference", /CPA-\d{4}-[A-F0-9]{12}/.test(await page.locator(".art-request-success").innerText()));
    check("Request confirmation explicitly takes no payment", (await page.locator(".art-request-success").innerText()).includes("Aucun paiement"));

    await context.addInitScript(({ token, user }) => { localStorage.setItem("token", token); localStorage.setItem("user", JSON.stringify(user)); }, { token: fixture.adminToken, user: fixture.adminUser });
    await page.goto(base + "/secure-admin-dashboard-2024/cp-art");
    await page.getByRole("heading", { name: "Catalogue des œuvres" }).waitFor();
    await page.getByRole("button", { name: "Modifier la fiche", exact: true }).filter({ visible: true }).first().waitFor();
    check("Protected Art module loads real administrator data", await page.getByRole("button", { name: "Modifier la fiche", exact: true }).count() === 2);
    await page.screenshot({ path: path.join(output, "admin-catalogue.png"), fullPage: true });
    const publicCard = page.locator(".MuiPaper-root").filter({ has: page.getByText("Œuvre de vérification QA", { exact: true }) }).last();
    await publicCard.getByRole("button", { name: "Modifier la fiche", exact: true }).click();
    await page.getByRole("dialog").waitFor();
    const prices = page.getByLabel("Prix public en EUR");
    await delaySafeFill(prices.first(), "89,50");
    check("Price editor accepts decimal commas", await prices.first().inputValue() === "89,50");
    const nextPhotoDescription = await page.getByLabel("Description photo 2 (FR)").inputValue();
    const nextFirstPhoto = await page.getByRole("dialog").locator("img").nth(1).getAttribute("src");
    await page.getByRole("button", { name: "Descendre photo 1", exact: true }).click();
    const photoDescription = page.getByLabel("Description photo 1 (FR)");
    check("Photo reordering keeps its associated description", await photoDescription.inputValue() === nextPhotoDescription);
    await page.getByRole("tab", { name: "EN", exact: true }).click();
    await page.getByLabel("Titre (EN)", { exact: true }).fill("QA artwork translated");
    await page.getByRole("tab", { name: "FR", exact: true }).click();
    await page.getByRole("button", { name: "Enregistrer la fiche", exact: true }).click();
    await page.getByRole("dialog").waitFor({ state: "hidden" });
    check("Catalogue editor saves translation, image order and price", (await page.getByText("La fiche a été enregistrée.").count()) > 0);

    await page.goto(base + "/secure-admin-dashboard-2024/cp-art-requests");
    await page.getByRole("heading", { name: "Demandes CP Art" }).waitFor();
    const requestCard = page.locator(".MuiPaper-root").filter({ has: page.getByRole("heading", { name: submittedReference, exact: true }) }).last();
    await requestCard.getByText("Client interface QA · interface@example.test", { exact: true }).waitFor();
    check("Customer selection appears in protected enquiry dashboard", await requestCard.getByText("Client interface QA · interface@example.test", { exact: true }).isVisible());
    await page.screenshot({ path: path.join(output, "admin-demandes.png"), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await open("/fr/art/oeuvres/oeuvre-verification");
    await page.locator(".art-photo-thumbnails button").first().waitFor();
    check("Saved photo order appears on public artwork", await page.locator(".art-product__canvas img").getAttribute("src") === nextFirstPhoto);
    check("Saved public price is current", (await page.locator(".art-real-price").innerText()).includes("89,50"));
    await page.getByRole("button", { name: "Ajouter à ma sélection", exact: true }).click();
    await page.locator(".art-selection-total").waitFor();
    check("Mobile selection fits the viewport", await page.locator(".art-selection-layout").evaluate(el => el.getBoundingClientRect().right <= innerWidth));
    await page.screenshot({ path: path.join(output, "selection-live-mobile.png"), fullPage: true });
    check("No uncaught browser errors", errors.length === 0);
    fs.writeFileSync(path.join(output, "verification-live.json"), JSON.stringify({ checks, errors, isolatedData: true }, null, 2));
    console.log(JSON.stringify({ passed: checks.length, checks }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
